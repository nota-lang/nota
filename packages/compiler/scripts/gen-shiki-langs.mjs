/**
 * Regenerate `src/shiki-langs.generated.ts` from the installed shiki.
 *
 *   node scripts/gen-shiki-langs.mjs
 *
 * The compiler auto-imports a grammar for every fenced language tag (`grammarBindings` in
 * src/lib.ts), so it has to know which tags name a real shiki grammar module: an unknown tag must
 * fall through to the runtime's warning rather than emit an import that fails to resolve and
 * breaks the build with a message pointing at generated code.
 *
 * The set is `@shikijs/langs`'s own subpath exports, which is exactly the set of
 * `@shikijs/langs/<name>` specifiers that resolve — aliases (`js`, `rs`, `sh`) included, which
 * matters because a fence tag is written the way a reader writes it, not canonicalised. Read off
 * the exports map rather than off `dist/`, because the exports map is what resolution consults:
 * `dist/` additionally holds `index.mjs`, which is not a grammar.
 *
 * Generated rather than imported: `@shikijs/langs`'s barrel carries a lazy `import()` thunk per
 * language, so pulling it in for a list of names would make a bundler emit 360 grammar chunks.
 * `tests/shiki-langs.test.ts` fails if this file drifts from the installed grammars.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require_ = createRequire(import.meta.url);

/** The `@shikijs/langs/<name>` subpaths the installed grammars package publishes, sorted. */
export function shikiLangNames() {
  // Located through a known member and read off disk: `@shikijs/langs` does not export
  // `./package.json`, so the manifest is not reachable as a specifier.
  const root = dirname(dirname(require_.resolve("@shikijs/langs/rust")));
  const { exports } = JSON.parse(
    readFileSync(join(root, "package.json"), "utf8")
  );
  return Object.keys(exports)
    .filter(key => key.startsWith("./") && key !== "./package.json")
    .map(key => key.slice("./".length))
    .sort();
}

const names = shikiLangNames();
writeFileSync(
  new URL("../src/shiki-langs.generated.ts", import.meta.url),
  `// Generated by scripts/gen-shiki-langs.mjs. Do not edit.
//
// Every \`@shikijs/langs/<name>\` specifier that resolves, aliases included. The compiler emits a
// grammar import only for a fence tag in this set; any other tag is left to the runtime, which
// warns and renders the block plain.

/** Fence tags the compiler can auto-import a shiki grammar for. */
export const SHIKI_LANG_MODULES: ReadonlySet<string> = new Set([
${names.map(n => `  ${JSON.stringify(n)}`).join(",\n")}
]);
`
);
console.log(`wrote ${names.length} names`);
