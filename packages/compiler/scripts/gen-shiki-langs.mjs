/**
 * Regenerate `src/shiki-langs.generated.ts` from the installed shiki.
 *
 *   node scripts/gen-shiki-langs.mjs
 *
 * The compiler auto-imports a grammar for every fenced language tag (`grammarBindings` in
 * src/lib.ts), so it has to know which tags name a real shiki grammar module: an unknown tag must
 * fall through to the runtime's warning rather than emit an import that fails to resolve and
 * breaks the build with a message pointing at generated code.
 *
 * The set is the basenames under shiki's own `dist/langs`, which is exactly the set of
 * `shiki/langs/<name>.mjs` specifiers that resolve — aliases (`js`, `rs`, `sh`) included, which
 * matters because a fence tag is written the way a reader writes it, not canonicalised.
 *
 * Generated rather than imported: `shiki/langs.mjs` carries a lazy `import()` thunk per language,
 * so pulling it in for a list of names would make a bundler emit 346 grammar chunks.
 * `tests/shiki-langs.test.ts` fails if this file drifts from the installed shiki.
 */

import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname } from "node:path";

const require_ = createRequire(import.meta.url);

/** The `shiki/langs/<name>.mjs` basenames the installed shiki publishes, sorted. */
export function shikiLangNames() {
  // Resolved through a known member: shiki's exports map does not expose the directory itself.
  const dir = dirname(require_.resolve("shiki/langs/rust.mjs"));
  return readdirSync(dir)
    .filter(f => f.endsWith(".mjs"))
    .map(f => f.slice(0, -".mjs".length))
    .sort();
}

const names = shikiLangNames();
writeFileSync(
  new URL("../src/shiki-langs.generated.ts", import.meta.url),
  `// Generated by scripts/gen-shiki-langs.mjs. Do not edit.
//
// Every \`shiki/langs/<name>.mjs\` specifier that resolves, aliases included. The compiler emits a
// grammar import only for a fence tag in this set; any other tag is left to the runtime, which
// warns and renders the block plain.

/** Fence tags the compiler can auto-import a shiki grammar for. */
export const SHIKI_LANG_MODULES: ReadonlySet<string> = new Set([
${names.map(n => `  ${JSON.stringify(n)}`).join(",\n")}
]);
`
);
console.log(`wrote ${names.length} names`);
